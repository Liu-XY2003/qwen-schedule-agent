#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
从 theme/tokens.json 生成两端的主题代码。

    python theme/gen_theme.py            # 写文件
    python theme/gen_theme.py --check    # 只校验是否已同步 (CI 用)

产物:
  bridge/static/theme.css                     网页版 (CSS 变量, 两套主题)
  ../AI_ScheduleAssistant/.../ui/theme/Tokens.kt   安卓版 (Compose Color)

为什么要有生成器: 网页版和 App 的配色一旦各改各的, 一两周就会走散
(这正是上一版 7 个模块色重复定义在两处的下场)。这里让 tokens.json
当唯一事实源, 生成物顶部带 "DO NOT EDIT" 头, --check 进 CI 就能防回退。
"""
import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TOKENS_PATH = ROOT / "tokens.json"
CSS_OUT = ROOT.parent / "bridge" / "static" / "theme.css"

# 安卓端在**另一个仓库**里。开源后两个仓库独立克隆, 后端 CI 里不会有
# AI_ScheduleAssistant 目录, 所以这个输出是可选的:
#   * 设了 SCHED_KT_OUT -> 按这个路径写 / 校验 (严格)
#   * 同级目录下存在 AI_ScheduleAssistant -> 写 / 校验 (本地开发)
#   * 都不满足 -> 跳过安卓侧, 只处理网页侧 (CI)
KT_ENV = "SCHED_KT_OUT"
KT_DEFAULT = (
    ROOT.parent.parent
    / "AI_ScheduleAssistant"
    / "app" / "src" / "main" / "java" / "com" / "liuxinyang"
    / "ai_scheduleassistant" / "ui" / "theme" / "Tokens.kt"
)


def kt_target() -> Path | None:
    """返回安卓输出路径; 该仓库不在场时返回 None (跳过)。"""
    env = os.environ.get(KT_ENV)
    if env:
        return Path(env)
    if KT_DEFAULT.parent.parent.exists():
        return KT_DEFAULT
    return None

# 与 Modules.colorIndex() 的顺序严格一致, 生成 Kotlin list 时按下标对齐
MODULE_ORDER = ["class", "exam", "meeting", "assignment", "alarm", "reminder", "memo"]
MODULE_KT = ["classColor", "examColor", "meetingColor", "assignmentColor",
             "alarmColor", "reminderColor", "memoColor"]

BANNER_CSS = "/* AUTO-GENERATED by theme/gen_theme.py from theme/tokens.json — DO NOT EDIT. */"
BANNER_KT = "// AUTO-GENERATED by theme/gen_theme.py from theme/tokens.json — DO NOT EDIT."


def _vars_for(t: dict) -> list[tuple[str, str]]:
    """把一个主题展开成 (CSS变量名, 值) 列表。"""
    c = t["colors"]
    out = [
        ("--bg", c["bg"]), ("--card", c["card"]), ("--card2", c["card2"]),
        ("--line", c["line"]), ("--fg", c["fg"]), ("--muted", c["muted"]),
        ("--accent", c["accent"]), ("--on-accent", c["onAccent"]),
        ("--chip-bg", c["chipBg"]),
        ("--ok", c["ok"]), ("--warn", c["warn"]), ("--danger", c["danger"]),
        ("--shadow", c["shadow"]),
    ]
    for m in MODULE_ORDER:
        out.append((f"--m-{m}", t["modules"][m]))
    r = t["radius"]
    out += [("--r-card", f'{r["card"]}px'), ("--r-btn", f'{r["button"]}px'),
            ("--r-cell", f'{r["cell"]}px'), ("--r-chip", f'{r["chip"]}px')]
    out += [("--font-title", t["font"]["title"]), ("--font-body", t["font"]["body"]),
            ("--num-variant", t["font"]["numberVariant"])]
    cc = t["calendarCell"]
    out += [("--marker-size", f'{cc["markerSize"]}px'),
            ("--marker-max", str(cc["maxMarkers"]))]
    out.append(("--ev-bar", f'{t["eventChip"]["barWidth"]}px'))
    out.append(("--dot-display",
                "inline-block" if cc["markerStyle"] == "dot" else "none"))
    out.append(("--dur", f'{t["motion"]["durationMs"]}ms'))
    return out


def gen_css(tokens: dict) -> str:
    default = tokens["defaultTheme"]
    lines = [BANNER_CSS, ""]
    for key, t in tokens["themes"].items():
        lines.append(f'/* ---- {t["label"]} ({key}) — {t["description"]} ---- */')
        # 默认主题同时挂到裸 :root 上, 保证 JS 还没跑/被禁用时页面也是对的
        sel = f':root[data-theme="{key}"]'
        if key == default:
            sel = ":root," + sel
        lines.append(f"{sel}{{")
        for name, val in _vars_for(t):
            lines.append(f"  {name}:{val};")
        lines.append("}")
        lines.append(f'{sel}{{color-scheme:{"dark" if t["isDark"] else "light"}}}')
        lines.append("")
    # 主题切换的过渡: 只过渡颜色, 别把布局也动了
    lines.append("body{transition:background var(--dur) ease-out,color var(--dur) ease-out}")
    lines.append("")
    return "\n".join(lines)


def _kt_color(hexval: str) -> str:
    h = hexval.lstrip("#")
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return f"Color(0xFF{h.upper()})"


def gen_kotlin(tokens: dict) -> str:
    L = [
        "package com.liuxinyang.ai_scheduleassistant.ui.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        BANNER_KT,
        "",
        "/** 一套完整配色。modules 的下标顺序 == Modules.colorIndex(), 由生成器保证。 */",
        "data class ThemePalette(",
        "    val key: String,",
        "    val label: String,",
        "    val isDark: Boolean,",
        "    val bg: Color,",
        "    val card: Color,",
        "    val card2: Color,",
        "    val line: Color,",
        "    val fg: Color,",
        "    val muted: Color,",
        "    val accent: Color,",
        "    val onAccent: Color,",
        "    val chipBg: Color,",
        "    val ok: Color,",
        "    val warn: Color,",
        "    val danger: Color,",
        "    val modules: List<Color>,",
        "    val cardRadius: Int,",
        "    val buttonRadius: Int,",
        "    val cellRadius: Int,",
        "    val markerBar: Boolean,",
        "    val markerSize: Int,",
        ") {",
        "    /** 与 Palette.of() 语义一致, 但走当前主题。 */",
        "    fun moduleOf(module: String): Color =",
        "        modules[com.liuxinyang.ai_scheduleassistant.data.Modules.colorIndex(module)]",
        "}",
        "",
        "object Tokens {",
    ]
    for key, t in tokens["themes"].items():
        c, r, cc = t["colors"], t["radius"], t["calendarCell"]
        mods = ",\n".join(
            f"            {_kt_color(t['modules'][m])}" for m in MODULE_ORDER
        )
        obj = key.upper()
        L += [
            f"    /** {t['label']} — {t['description']} */",
            f"    val {obj} = ThemePalette(",
            f'        key = "{key}",',
            f'        label = "{t["label"]}",',
            f'        isDark = {"true" if t["isDark"] else "false"},',
            f'        bg = {_kt_color(c["bg"])},',
            f'        card = {_kt_color(c["card"])},',
            f'        card2 = {_kt_color(c["card2"])},',
            f'        line = {_kt_color(c["line"])},',
            f'        fg = {_kt_color(c["fg"])},',
            f'        muted = {_kt_color(c["muted"])},',
            f'        accent = {_kt_color(c["accent"])},',
            f'        onAccent = {_kt_color(c["onAccent"])},',
            f'        chipBg = {_kt_color(c["chipBg"])},',
            f'        ok = {_kt_color(c["ok"])},',
            f'        warn = {_kt_color(c["warn"])},',
            f'        danger = {_kt_color(c["danger"])},',
            f"        // 顺序: {', '.join(MODULE_ORDER)}",
            "        modules = listOf(",
            mods + ",",
            "        ),",
            f'        cardRadius = {r["card"]},',
            f'        buttonRadius = {r["button"]},',
            f'        cellRadius = {r["cell"]},',
            f'        markerBar = {"true" if cc["markerStyle"] == "bar" else "false"},',
            f'        markerSize = {cc["markerSize"]},',
            "    )",
            "",
        ]
    default = tokens["defaultTheme"]
    L += [
        f'    val DEFAULT_KEY = "{default}"',
        "    val all: List<ThemePalette> = listOf(PAPER, NIGHT)",
        f"    val default: ThemePalette = {default.upper()}",
        "",
        "    fun byKey(key: String): ThemePalette =",
        "        all.firstOrNull { it.key == key } ?: default",
        "}",
        "",
    ]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验生成物是否最新")
    ap.add_argument("--kt-out", help=f"安卓 Tokens.kt 的输出路径 (等价于环境变量 {KT_ENV})")
    args = ap.parse_args()

    if args.kt_out:
        os.environ[KT_ENV] = args.kt_out

    tokens = json.loads(TOKENS_PATH.read_text(encoding="utf-8"))
    wanted = {CSS_OUT: gen_css(tokens)}

    kt = kt_target()
    if kt is not None:
        wanted[kt] = gen_kotlin(tokens)
    else:
        print(f"跳过安卓侧 (未设 {KT_ENV}, 且同级目录下没有 AI_ScheduleAssistant 仓库)")

    if args.check:
        bad = []
        for path, content in wanted.items():
            if not path.exists():
                bad.append(f"缺失: {path}")
            elif path.read_text(encoding="utf-8") != content:
                bad.append(f"过期: {path} (跑 python theme/gen_theme.py)")
        if bad:
            print("主题未同步:")
            for b in bad:
                print("  -", b)
            return 1
        print(f"主题已同步 ({len(wanted)} 个产物)")
        return 0

    for path, content in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"写出 {path}  ({len(content)} 字节)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
